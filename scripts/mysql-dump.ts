import { createHash } from 'node:crypto';

export type Cell = string | number | null;
export type Table = { name: string; columns: string[]; rows: Cell[][]; nextId: number };
export const ident = (value: string) => '"' + value.replaceAll('"', '""') + '"';
export const literal = (value: Cell): string => value === null ? 'NULL' : typeof value === 'number' ? String(value) : "'" + value.replaceAll("'", "''") + "'";

/** Parse phpMyAdmin INSERT tuples as data, never as executable JavaScript. */
export function readTuples(input: string): Cell[][] {
  let i = 0;
  const rows: Cell[][] = [];
  const space = () => { while (/\s/.test(input[i] ?? '') && i < input.length) i++; };
  while (i < input.length) {
    space();
    if (input[i] === ';') break;
    if (input[i++] !== '(') throw new Error('Expected INSERT tuple');
    const row: Cell[] = [];
    while (i < input.length) {
      space();
      let value: Cell;
      if (input[i] === "'") {
        i++;
        let text = '', closed = false;
        while (i < input.length) {
          const char = input[i++];
          if (char === '\\') {
            const next = input[i++];
            const escapes: Record<string, string> = { '0': '\0', b: '\b', n: '\n', r: '\r', t: '\t', Z: '\x1a' };
            text += escapes[next] ?? (next === '%' || next === '_' ? '\\' + next : next);
          } else if (char === "'") {
            if (input[i] === "'") { text += "'"; i++; } else { closed = true; break; }
          } else text += char;
        }
        if (!closed) throw new Error('Unterminated dump string');
        if (text.includes('\0')) throw new Error('NUL byte requires manual migration review');
        value = text;
      } else {
        const start = i;
        while (i < input.length && input[i] !== ',' && input[i] !== ')') i++;
        const token = input.slice(start, i).trim();
        if (token === 'NULL') value = null;
        else if (/^-?\d+(?:\.\d+)?$/.test(token)) {
          // Keep decimal values as strings to preserve money exactly in the export.
          value = token.includes('.') ? token : Number(token);
          if (typeof value === 'number' && !Number.isSafeInteger(value)) throw new Error('Unsafe integer in dump');
        } else throw new Error('Unsupported dump value');
      }
      row.push(value);
      space();
      if (input[i] === ')') { i++; break; }
      if (input[i++] !== ',') throw new Error('Expected value separator');
    }
    rows.push(row);
    space();
    if (input[i] === ',') { i++; continue; }
    if (input[i] === ';' || i === input.length) break;
    throw new Error('Expected tuple separator');
  }
  return rows;
}

export function convertDump(source: string) {
  const tables: Table[] = [];
  const ddl = [
    `CREATE FUNCTION public.app_now() RETURNS timestamp LANGUAGE sql STABLE AS $$ SELECT timezone('Asia/Ulaanbaatar', now()) $$;`,
    `CREATE FUNCTION public.app_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated_at = public.app_now(); RETURN NEW; END $$;`,
  ];
  let zeroDates = 0;
  const dateColumns = new Map<string, Set<string>>();
  for (const match of source.matchAll(/CREATE TABLE `(\w+)` \(\r?\n([\s\S]*?)\r?\n\) ENGINE[^;]+;/g)) {
    const [, name, body] = match;
    const columns: string[] = [], definitions: string[] = [];
    const dates = new Set<string>();
    let touch = false;
    for (const line of body.split(/\r?\n/)) {
      const column = line.match(/^\s*`(\w+)` (.+?)(?:,)?$/);
      if (!column) throw new Error(`Unsupported column in ${name}`);
      const [, key] = column;
      let type = column[2].replace(/,$/, '');
      columns.push(key);
      if (/^(date|datetime|timestamp)\b/.test(type)) dates.add(key);
      if (/ON UPDATE CURRENT_TIMESTAMP/.test(type)) touch = true;
      type = type.replace(/ COLLATE \w+/g, '').replace(/ ON UPDATE CURRENT_TIMESTAMP/g, '')
        .replace(/\bCURRENT_TIMESTAMP\b/g, 'public.app_now()')
        .replace(/\bdatetime\b/g, 'timestamp without time zone')
        .replace(/\btimestamp\b(?! without)/g, 'timestamp without time zone')
        .replace(/\btinyint(?:\(1\))?/g, 'smallint').replace(/\blongtext\b/g, 'text');
      if (/\bUNSIGNED\b/.test(type)) type = type.replace(/ UNSIGNED/g, '') + ` CHECK (${ident(key)} >= 0)`;
      const en = type.match(/^enum\(([^)]+)\)/);
      if (en) type = type.replace(/^enum\([^)]+\)/, 'text') + ` CHECK (${ident(key)} IN (${en[1]}, ''))`;
      if (key === 'id') type = type.replace(/ NOT NULL/, ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
      definitions.push(`  ${ident(key)} ${type}`);
    }
    dateColumns.set(name, dates);
    const increment = source.match(new RegExp('ALTER TABLE `' + name + '`\\s+MODIFY `id`[^;]*?AUTO_INCREMENT=(\\d+)'));
    tables.push({ name, columns, rows: [], nextId: Number(increment?.[1] ?? 1) });
    ddl.push(`CREATE TABLE public.${ident(name)} (\n${definitions.join(',\n')}\n);`);
    if (touch) ddl.push(`CREATE TRIGGER touch_updated_at BEFORE UPDATE ON public.${ident(name)} FOR EACH ROW EXECUTE FUNCTION public.app_touch_updated_at();`);
    // Access is exclusively through trusted Next server code, not Supabase's public Data API.
    ddl.push(`ALTER TABLE public.${ident(name)} ENABLE ROW LEVEL SECURITY;`);
  }
  if (tables.length !== 16) throw new Error(`Expected 16 tables, found ${tables.length}`);
  for (const match of source.matchAll(/ALTER TABLE `(\w+)`\s+([\s\S]*?);/g)) {
    const [, table, body] = match;
    for (const index of body.matchAll(/ADD (UNIQUE )?KEY `(\w+)` \(([^)]+)\)/g)) {
      const [, unique, name, cols] = index;
      let columns = cols.replaceAll('`', '"');
      if ((table === 'users' && name === 'email') || (table === 'leagues' && name === 'slug')) columns = `LOWER(${columns})`;
      ddl.push(`CREATE ${unique ? 'UNIQUE ' : ''}INDEX ${ident(table + '_' + name)} ON public.${ident(table)} (${columns});`);
    }
  }
  // Match full INSERT statements while respecting semicolons inside quoted data.
  const inserts = /INSERT INTO `(\w+)` \(([^)]+)\) VALUES\s*((?:'(?:\\[\s\S]|''|[^'\\])*'|[^';])+);/g;
  for (const match of source.matchAll(inserts)) {
    const table = tables.find((t) => t.name === match[1]);
    if (!table) throw new Error('Unknown INSERT table');
    const cols = [...match[2].matchAll(/`(\w+)`/g)].map((m) => m[1]);
    if (JSON.stringify(cols) !== JSON.stringify(table.columns)) throw new Error(`Column order mismatch: ${table.name}`);
    for (const row of readTuples(match[3])) {
      if (row.length !== cols.length) throw new Error(`Column count mismatch: ${table.name}`);
      row.forEach((value, i) => {
        if (dateColumns.get(table.name)!.has(cols[i]) && typeof value === 'string' && /^0000-00-00/.test(value)) { row[i] = null; zeroDates++; }
      });
      table.rows.push(row);
    }
  }
  const expectedInserts = (source.match(/^INSERT INTO /gm) ?? []).length;
  if ([...source.matchAll(inserts)].length !== expectedInserts) throw new Error('Not every INSERT was parsed');
  const sequenceSql = tables.map((t) => `SELECT setval(pg_get_serial_sequence('public.${t.name}', 'id'), GREATEST(${t.nextId}, COALESCE((SELECT MAX(id) + 1 FROM public.${ident(t.name)}), 1)), false);`).join('\n');
  const report = { sourceSha256: createHash('sha256').update(source).digest('hex'), zeroDatesConvertedToNull: zeroDates,
    tables: tables.map((t) => ({ name: t.name, rows: t.rows.length })), totalRows: tables.reduce((n, t) => n + t.rows.length, 0) };
  return { tables, schema: ddl.join('\n\n'), sequenceSql, report };
}

export function dataSql(tables: Table[]) {
  return tables.flatMap((table) => {
    const batches: string[] = [];
    for (let i = 0; i < table.rows.length; i += 200) {
      batches.push(`INSERT INTO public.${ident(table.name)} (${table.columns.map(ident).join(',')}) VALUES\n` +
        table.rows.slice(i, i + 200).map((row) => '(' + row.map(literal).join(',') + ')').join(',\n') + ';');
    }
    return batches;
  }).join('\n\n');
}
